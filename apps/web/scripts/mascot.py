"""Edit and run `python3 scripts/mascot.py` from apps/web: writes src/PixelAgent.tsx, public/favicon.svg, scripts/mascot.svg.
Original mascot inspired by a modular micro-robot unit: ball joints + tapered cone limbs. -> mascot.svg"""
import math, os
os.chdir(os.path.dirname(os.path.abspath(__file__)))
W, H = 32, 38
PAL = {"I": "#4f46e5", "L": "#818cf8", "D": "#312e81", "K": "#1e1b4b", "F": "#ffffff", "E": "#22d3ee", "A": "#f59e0b", "N": "#0b0b12", "V": "#cbd5e1", "X": "#f1f5f9", "Z": "#94a3b8", "P": "#8b93f8", "Q": "#c7d2fe", "R": "#5b5fd6", "w": "#fbf8f2", "o": "#a39a8e", "s": "#e9e2d7", "h": "#ffffff", "b": "#3b2f2a", "p": "#f4a6a6"}
g = [["."] * W for _ in range(H)]
def px(x, y, c):
    if 0 <= x < W and 0 <= y < H: g[y][x] = c
def ball(cx, cy, r, body="I", hi="L", lo="D"):
    for y in range(H):
        for x in range(W):
            d = math.hypot(x + .5 - cx, y + .5 - cy)
            if d <= r:
                c = body
                if d > r - 1 and (x + .5 < cx and y + .5 < cy): c = hi
                elif d > r - 1 and (x + .5 > cx or y + .5 > cy): c = lo
                px(x, y, c)
def cone(x0, y0, x1, y1, w0):  # tapered limb, thick at (x0,y0)
    n = int(max(abs(x1 - x0), abs(y1 - y0)) * 3)
    for i in range(n + 1):
        t = i / n; cx = x0 + (x1 - x0) * t; cy = y0 + (y1 - y0) * t; r = w0 + 0.6
        for y in range(H):
            for x in range(W):
                if math.hypot(x + .5 - cx, y + .5 - cy) <= r: px(x, y, "I")
# cone limbs: thick end at the joint, sharp tip outward; separate from the torso ball
cone(11, 18, 7, 23, 1.9); cone(21, 18, 25, 23, 1.9)      # arms
cone(13, 25.5, 12.5, 30.5, 2.0); cone(19, 25.5, 19.5, 30.5, 2.0)    # legs
for (ex, ey) in [(7, 23), (25, 23), (12, 31), (20, 31)]:
    ball(ex, ey, 2.6)                                   # round limb ends
ball(16, 20.5, 3.4)                                     # torso = central ball joint
ball(16, 21, 2.0, "V", "X", "Z")                          # belly light
for (cx, cy) in [(11, 18), (21, 18)]:
    ball(cx, cy, 1.5, "V", "X", "Z")                              # shoulder joints
for (cx, cy) in [(13, 25), (19, 25)]:
    ball(cx, cy, 1.5, "K")                              # joints
ball(16, 11, 5.3)                                        # head
for (x, y) in [(13, 11), (13, 12), (18, 11), (18, 12)]: px(x, y, "F")
px(14, 12, "E"); px(19, 12, "E")
px(16, 17, "K")                                          # neck
full = [r[:] for r in g]
HS = 18                                                 # head only: its own 18x18 grid
g = [["."] * HS for _ in range(HS)]
for y in range(HS):                                     # soft ivory head: outline, warm shade low-right, highlight top-left
    for x in range(HS):
        d = math.hypot(x + .5 - 9, y + .5 - 9)
        if d <= 8.4:
            c = "w"
            if d > 7.4: c = "o"
            elif d > 6.0 and (x + .5 > 9 and y + .5 > 9): c = "s"
            elif d > 5.6 and x + .5 < 8 and y + .5 < 6: c = "h"
            g[y][x] = c
for (x, y) in [(4, 9), (5, 8), (6, 8), (7, 9), (10, 9), (11, 8), (12, 8), (13, 9)]:
    g[y][x] = "b"                                       # smiling closed eyes, like ^ ^
for (x, y) in [(3, 11), (4, 11), (13, 11), (14, 11)]:
    g[y][x] = "p"                                       # blush
head = g
g = full
def runs(grid):
    rows = ["".join(r) for r in grid]
    W = len(rows[0])
    out = []
    for y, row in enumerate(rows):
        x = 0
        while x < W:
            c = row[x]
            if c == ".": x += 1; continue
            s0 = x
            while x < W and row[x] == c: x += 1
            out.append(f'<rect x="{s0}" y="{y}" width="{x-s0}" height="1" fill="{PAL[c]}"/>')
    return out
head_rects = runs(head)
rects = runs(g)
body = "".join(rects)
open("mascot.svg", "w").write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W*10}" height="{H*10}" shape-rendering="crispEdges">' + body + "</svg>")
# favicon: the head only (reads at 16px)
hb = "".join(head_rects)
open("../public/favicon.svg", "w").write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 18 18" shape-rendering="crispEdges">' + hb + "</svg>\n")
tsx = "\n".join("      " + r.replace('"/>', '" />') for r in head_rects)
open("../src/PixelAgent.tsx", "w").write(f"""// Generated by scripts/mascot.py, do not edit by hand.
/** The simp-agent mascot: the head of the modular bot. */
export function PixelAgent({{ size = 32, className }}: {{ size?: number; className?: string }}) {{
  return (
    <svg viewBox="0 0 18 18" width={{size}} height={{size}} shapeRendering="crispEdges" className={{className}}
      aria-hidden="true" focusable="false">
{tsx}
    </svg>
  );
}}
""")
